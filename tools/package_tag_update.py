"""Build a configuration-free update ZIP from the verified release outputs."""
from pathlib import Path
import hashlib
import zipfile

ROOT = Path(__file__).resolve().parent.parent
GAME = ROOT.parent.parent
BIN = ROOT / "build/release/bin"
INSTRUCTION = """SA:COOP 0.3.1.8 — ДОГОНЯЛКИ С ВРЕМЕННОЙ ВЫНОСЛИВОСТЬЮ (протокол 25)

ВЫНОСЛИВОСТЬ В МИНИИГРЕ
На время режима оба игрока получают 100% навыка выносливости.
При входе и перед каждым раундом запас сил для бега полностью заполняется.
При /endgames или отмене возвращаются прежние навык, запас сил и прогресс тренировки.
Временный навык не сохраняется в профиль и сюжетное сохранение.
В раунде силы расходуются по обычным правилам GTA с максимальным навыком.
Протокол не менялся (25); оба клиента обновите до 0.3.1.8 ради одинаковой выносливости.

ИСПРАВЛЕНО
Отдельная загрузка земли/коллизий перед телепортом и возвратом.
Если площадка не подходит — до четырёх общих попыток, без смены ролей и точек возврата.
Причина отмены теперь видна обоим игрокам и записывается в логи.
На этапе проверки готовности больше нет краткого чёрного экрана.
С 0.3.1.6 и более старыми версиями протокол несовместим.

УСТАНОВКА ДРУГУ
1. Закрой GTA и сервер SA:COOP.
2. Сохрани копию старых coop.asi, coop/coop-server.exe и coop/coop.pdb.
3. Распакуй этот архив в папку с gta_sa.exe, согласись на замену.
   coop.asi должен оказаться рядом с gta_sa.exe; сервер и pdb — в подпапке coop.
4. Обновиться должны оба игрока. Сборки с протоколом до 25 не подключатся.
   Настройки, профили и сохранения архив не содержит и не заменяет.
   SilentPatchSA и FramerateVigilante оставь установленными.

ДОГОНЯЛКИ
Сохрани сюжет перед первым игровым тестом.
Оба игрока должны стоять на земле на улице, без миссии, розыска, AFK и помощи раненому.
Не стойте в маркере миссии. Подключитесь к одному общему миру.

/minigames — начать. Оба телепортируются рядом в случайную локацию карты.
Беглецу даются 35 секунд на прятки, догоняющий заморожен перед чёрным экраном.
Затем у догоняющего 10 минут: попал кулаком один раз — выиграл.
Кастет также считается. Удар не снимает здоровье; friendly fire включать не нужно.
Если время истекло, выигрывает беглец.
Метка беглеца и ник/HP/броня над его головой скрыты до результата раунда.
Через 5 секунд роли меняются, выбирается новая площадка и начинается новый раунд.

/endgames — остановить режим у обоих и вернуть каждого туда, где он стоял до /minigames.
Восстанавливаются здоровье, броня, деньги, характеристики, оружие и патроны.
При чёрном экране команду можно ввести в чат вслепую.

Во время режима приостановлены SCM, подбор предметов, входы в интерьеры и сохранение.
Не работают посадка в транспорт, AFK, revive, передачи и обычные телепорты.
При потере связи оставшийся игрок возвращается в обычную игру.
Трафик, погода, время и NPC продолжают жить; полный откат мира/других модов не выполняется.
Не применяйте чит-коды. Подробности и сценарий проверки: docs/TAG-MINIGAME.md.

ПРЕЖНИЕ ОБНОВЛЕНИЯ ТОЖЕ ВКЛЮЧЕНЫ
/pay <id> <сумма>, /afk, /givegun, /giveammo <число>, ранения,
/revive и поднятие кнопкой E, /giveup, свободная камера в AFK и при ранении.

ПРОВЕРКИ
Пройдены сборка и автоматические тесты таймеров/сети/старых команд.
Автотесты не запускают GTA: реальный удар, чёрный экран и возврат нужно проверить вдвоём в игре.
При первом тесте: проверьте один удар, смену ролей, /endgames, затем сюжетный маркер и управление.

ОТКАТ
Закрой игру и сервер, верни прежние три файла из своей резервной копии.
Оба участника должны использовать одинаковую версию.
"""

def main():
    files = {
        "coop.asi": (BIN / "coop.dll").read_bytes(),
        "coop/coop-server.exe": (BIN / "coop-server.exe").read_bytes(),
        "coop/coop.pdb": (BIN / "coop.pdb").read_bytes(),
        "ДОГОНЯЛКИ-УСТАНОВКА.txt": INSTRUCTION.encode("utf-8-sig"),
    }
    for path in sorted((ROOT / "docs").glob("*.md")):
        files[f"docs/{path.name}"] = path.read_bytes()
    for path in sorted((ROOT / "dist/SA-COOP/coop/licenses").glob("*.txt")):
        files[f"coop/licenses/{path.name}"] = path.read_bytes()
    manifest = "\n".join(f"{hashlib.sha256(data).hexdigest()}  {name}" for name, data in files.items())+"\n"
    files["SHA256SUMS.txt"] = manifest.encode("utf-8")
    out = GAME / "SA-COOP-TagGame-stamina-update.zip"
    with zipfile.ZipFile(out,"w",zipfile.ZIP_DEFLATED) as archive:
        for name,data in files.items():
            archive.writestr(name,data)
    with zipfile.ZipFile(out) as archive:
        assert archive.testzip() is None
        for name,data in files.items():
            assert archive.read(name)==data, name
    (GAME / "ДОГОНЯЛКИ-УСТАНОВКА.txt").write_bytes(files["ДОГОНЯЛКИ-УСТАНОВКА.txt"])
    print(f"Update ZIP: {out.name} ({out.stat().st_size} bytes); {len(files)} entries verified")

if __name__=="__main__":
    main()
